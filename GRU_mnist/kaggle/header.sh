#!/usr/bin/env bash
# =============================================================================
# Data-poisoning testbed on krum — self-contained Kaggle runner.
#
# Usage, in a Kaggle notebook (Accelerator: GPU T4, Internet: ON):
#     !bash run_kaggle.sh            # = sanity: setup, tests, calibrate C, Step 2 grid, table
#     !bash run_kaggle.sh collect    # Step 3: randomized collection (720 runs)
#     !bash run_kaggle.sh all        # both, in sequence
#     !bash run_kaggle.sh counterfactual   # GRU check 3: 384 runs, test seeds x candidate schedules
#     !bash run_kaggle.sh xp2              # xp2: 260 runs, windowed backdoor + Krum, data with kills
#     !bash run_kaggle.sh xp3              # xp3: 400 runs, stealthy backdoors, probes, paired twins
#     !bash run_kaggle.sh xp4              # xp4: 400 runs, xp3 design + signals v2 (memory/tail signals), onset-focused
#     !bash run_kaggle.sh xp5_pilot        # xp5 pilot: Fashion-MNIST, 8 attacks x Krum/Median/TrimmedMean (162 runs)
#                                          #   -> /kaggle/working/xp5_pilot.zip
#     !bash run_kaggle.sh xp5_data         # xp5 step 1: 600 runs (Fashion-MNIST, 5 attack families x 3 defenses)
#                                          #   -> /kaggle/working/results_xp5_data.zip   (~6.5 h)
#     !bash run_kaggle.sh xp5_final        # xp5 step 2: single mixed GRU + deployment + pilot -> xp5_all.zip
#                                          #   needs results_xp5_data.zip attached as a dataset (Add Input) (~5.5 h)
#     !bash run_kaggle.sh xp5a             # xp5a: GRU retrained without react/probehold schedules + benefit check
#                                          #   + GRU deployment (end rule 'freeze') -> xp5a_all.zip
#                                          #   needs xp5_all.zip attached as a dataset (Add Input) (~2 h)
#     !bash run_kaggle.sh xp6              # xp6: data (500 runs, Krum, backdoor + label flip, alarm-driven schedules)
#                                          #   + GRU + deployment in one session -> xp6_all.zip (~8.5 h)
#     !bash run_kaggle.sh xp6_data         #   the same in two sessions: data -> results_xp6_data.zip + xp6_all.zip (~5.5 h)
#     !bash run_kaggle.sh xp6_final        #   GRU + deployment; needs results_xp6_data.zip attached (~3 h)
#     !bash run_kaggle.sh xp3_deploy       # GRU sweep on xp3 + model selection + deployment (96 runs)
#                                          #   needs results_xp3.zip attached as a Kaggle dataset (Add Input)
#                                          #   -> /kaggle/working/xp3_deploy.zip
#
# Optional environment variables:
#     JOBS=4          parallel runs (default: number of CPUs)
#     WORK=/path      output folder (default: /kaggle/working/testbed)
#     EXTRA="--set sigma=0.02 --set sign_flip_scale=5"   config overrides for sanity/collect
#     XP3_DATA=/path/all_blocks.csv   xp3 data for xp3_deploy (default: searched in /kaggle/input)
#     XP5_DATA=/path/all_blocks.csv   xp5 data for xp5_final (default: searched in /kaggle/input)
#     XP5_SMOKE=1     tiny version of the xp5 stages (30-block runs, 2 epochs): checks the pipeline end to end
#     XP6_SMOKE=1     the same for the xp6 stages
#     XP6_DATA=/path/all_blocks.csv   xp6 data for xp6_final (default: this session's, else /kaggle/input)
#
# Re-running a stage skips runs that already finished with the same config,
# so an interrupted stage can simply be started again (same session).
# The source of the testbed is embedded below and written to $WORK on each run.
# Generated by kaggle/build.sh from the project sources — do not edit by hand.
# =============================================================================
set -euo pipefail

STAGE="${1:-sanity}"
case "$STAGE" in sanity|collect|all|counterfactual|xp2|xp3|xp4|xp5_pilot|xp5_data|xp5_final|xp5a|xp6_data|xp6_final|xp6|xp3_deploy) ;; *) echo "usage: $0 [sanity|collect|all|counterfactual|xp2|xp3|xp4|xp5_pilot|xp5_data|xp5_final|xp5a|xp6_data|xp6_final|xp6|xp3_deploy]"; exit 2;; esac
if [ -d /kaggle/working ]; then DEFAULT_WORK=/kaggle/working/testbed; else DEFAULT_WORK="$PWD/testbed"; fi
WORK="${WORK:-$DEFAULT_WORK}"
JOBS="${JOBS:-$(nproc)}"
EXTRA="${EXTRA:-}"
VENV="$WORK/.venv"
# Kaggle notebooks export MPLBACKEND=module://matplotlib_inline...; that backend is not in our venv.
export MPLBACKEND=Agg
PY="$VENV/bin/python"

echo "== stage=$STAGE  work=$WORK  jobs=$JOBS  extra='$EXTRA'"
mkdir -p "$WORK"
cd "$WORK"

# ---------------------------------------------------------------------------
# 1. Environment: Python 3.12 venv with the exact versions used locally.
#    (krum 0.10.0 needs Python >= 3.12 and torch >= 2.13; Kaggle's image may not.)
# ---------------------------------------------------------------------------
if [ ! -x "$PY" ]; then
  echo "== creating Python 3.12 environment"
  pip install -q uv
  uv venv --python 3.12 "$VENV"
  uv pip install --python "$PY" torch==2.14.1 torchvision==0.29.1 --index-url https://download.pytorch.org/whl/cu126
  uv pip install --python "$PY" krum==0.10.0 pandas pyarrow matplotlib scikit-learn pytest
fi
"$PY" - <<'PYCHECK'
import torch, krum
print(f"python ok | torch {torch.__version__} | krum {krum.__version__} | cuda {torch.cuda.is_available()}")
if not torch.cuda.is_available():
    raise SystemExit("No CUDA GPU visible: set Accelerator to 'GPU T4' in the notebook settings.")
x = torch.randn(256, 256, device="cuda"); (x @ x).sum().item()   # fails fast on an unsupported GPU
print("gpu:", torch.cuda.get_device_name(0))
PYCHECK

# ---------------------------------------------------------------------------
# 2. Testbed source (embedded).
# ---------------------------------------------------------------------------
echo "== writing testbed source"
mkdir -p poison_testbed tests
