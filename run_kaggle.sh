CF_SCHEDULE = re.compile(r"cf_(on|off|ontil20|offtil20|alt)_p(\d+)")
PROBE_SCHEDULE = re.compile(r"probe_P(\d+)_L(\d+)_o(\d+)")
PROBEHOLD_SCHEDULE = re.compile(r"probehold_P(\d+)_L(\d+)_o(\d+)_d(-?\d+)_e(\d+)")
