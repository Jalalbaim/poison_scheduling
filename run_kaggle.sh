        h = self.model.encode(data.enc.to(self.device))[:, b]  # state after rows 0..b = blocks -1..b-1
        H = min(self.horizon, N_BLOCKS - b)
        plans = {"probe": [int(is_probe(k)) for k in range(b, b + H)], "defend": [1] * H}
        W = np.zeros((2, N_ROWS))
