    chosen = [(c, "none" if c.attack == "none" else "attacked") for c, t in zip(main, test_split(main)) if t]
    chosen += [(c, "heldout") for c in heldout]
    out, rows = [], []
    for base, group in chosen:
        onset, n = base.window[0], base.n_blocks
