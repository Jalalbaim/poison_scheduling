#!/usr/bin/env bash
# =============================================================================
# CPC_DP — self-contained Kaggle runner (testbed from GRU_mnist, unchanged; CPC_DP scripts).
#
# Usage, in a Kaggle notebook (Accelerator: GPU T4, Internet: ON):
#     !bash run_kaggle_cpc.sh xp6_eval   # evaluation-only onset twins of xp6: 555 runs (53 attacked test seeds x 7,
#                                        #   16 no-attack test seeds x 4, 40 held-out seeds x 3) -> xp6_eval.zip (~6 h)
#     !bash run_kaggle_cpc.sh xp7_a      # xp7 main runs, gamma 0 and 2: 400 runs -> xp7_a.zip (~4 h)
#     !bash run_kaggle_cpc.sh xp7_b      # xp7 main runs, gamma 8 and hard alarm: 400 runs -> xp7_b.zip (~4 h)
#     !bash run_kaggle_cpc.sh xp7_twins  # xp7 onset twins, val + test setups: 264 runs -> xp7_twins.zip (~3 h)
#   The three xp7 stages are independent: run them in parallel sessions or one after another.
#     !bash run_kaggle_cpc.sh xp7_deploy # deployment of 4 trained models (embedded) as Krum controllers:
#                                        #   9 environments x 3 seeds x 9 policies, 225 runs -> xp7_deploy.zip (~2.5-3 h)
#     !bash run_kaggle_cpc.sh xp8_1      # xp8 session 1: 132 setups x (Krum off, Krum on) trunks + 996 paired
#                                        #   branches (save / resume) -> xp8_part1.zip (~9.5 h; stops new jobs at 11 h)
#     !bash run_kaggle_cpc.sh xp8_2      # xp8 session 2: the other 132 setups -> xp8_part2.zip (~9.5 h)
#   The two xp8 sessions are independent: run them in parallel or one after another.
#
# Same WORK and venv as GRU_mnist's run_kaggle.sh: both scripts can run in one notebook (e.g. xp6 then xp6_eval
# in two sessions, or this one alone). Never feed xp6_eval runs to training or model selection: they are placed
# relative to the true attack window.
#
# Optional environment variables:
#     JOBS=4          parallel runs (default: number of CPUs)
#     WORK=/path      output folder (default: /kaggle/working/testbed)
#     CPC_SMOKE=1     tiny version (a few runs of 30 blocks; xp8: 6 setups of 40 steps): checks the pipeline end to end
#     XP8_BUDGET_H=11 xp8: hours after which no new job starts (finished jobs are always zipped)
#
# Re-running a stage skips runs that already finished with the same config (same session).
# Generated by kaggle/build.sh from the project sources — do not edit by hand.
# =============================================================================
set -euo pipefail

STAGE="${1:-xp6_eval}"
case "$STAGE" in xp6_eval|xp7_a|xp7_b|xp7_twins|xp7_deploy|xp8_1|xp8_2) ;; *) echo "usage: $0 [xp6_eval|xp7_a|xp7_b|xp7_twins|xp7_deploy|xp8_1|xp8_2]"; exit 2;; esac
if [ -d /kaggle/working ]; then DEFAULT_WORK=/kaggle/working/testbed; else DEFAULT_WORK="$PWD/testbed"; fi
WORK="${WORK:-$DEFAULT_WORK}"
JOBS="${JOBS:-$(nproc)}"
VENV="$WORK/.venv"
export MPLBACKEND=Agg
PY="$VENV/bin/python"

echo "== stage=$STAGE  work=$WORK  jobs=$JOBS"
mkdir -p "$WORK"
cd "$WORK"

# ---------------------------------------------------------------------------
# 1. Environment: Python 3.12 venv with the exact versions used locally (as GRU_mnist/kaggle/header.sh).
# ---------------------------------------------------------------------------
if [ ! -x "$PY" ]; then
  echo "== creating Python 3.12 environment"
  pip install -q uv
  uv venv --python 3.12 "$VENV"
  uv pip install --python "$PY" torch==2.14.1 torchvision==0.29.1 --index-url https://download.pytorch.org/whl/cu126
  uv pip install --python "$PY" krum==0.10.0 pandas pyarrow matplotlib scikit-learn pytest
fi
"$PY" - <<'PYCHECK'
import torch, krum
print(f"python ok | torch {torch.__version__} | krum {krum.__version__} | cuda {torch.cuda.is_available()}")
if not torch.cuda.is_available():
    raise SystemExit("No CUDA GPU visible: set Accelerator to 'GPU T4' in the notebook settings.")
x = torch.randn(256, 256, device="cuda"); (x @ x).sum().item()   # fails fast on an unsupported GPU
print("gpu:", torch.cuda.get_device_name(0))
PYCHECK

# ---------------------------------------------------------------------------
# 2. Source (embedded): GRU_mnist testbed + CPC_DP scripts, flat in $WORK.
# ---------------------------------------------------------------------------
echo "== writing source"
mkdir -p poison_testbed tests cpc
